        if "stow_angle" in s1: self.s1_stow = int(s1["stow_angle"])
        elif "s1_stow" in servos_cfg: self.s1_stow = int(servos_cfg["s1_stow"])
        if "down_angle" in s1: self.s1_down = int(s1["down_angle"])
        elif "s1_down" in servos_cfg: self.s1_down = int(servos_cfg["s1_down"])
        if "min_angle" in s1: self.s1_min = int(s1["min_angle"])
        elif "s1_min" in servos_cfg: self.s1_min = int(servos_cfg["s1_min"])
        if "max_angle" in s1: self.s1_max = int(s1["max_angle"])
        elif "s1_max" in servos_cfg: self.s1_max = int(servos_cfg["s1_max"])
        if "center_angle" in s1: self.s1_center = int(s1["center_angle"])
        elif "s1_center" in servos_cfg: self.s1_center = int(servos_cfg["s1_center"])

        # S2 (Elbow)
        if "stow_angle" in s2: self.s2_stow = int(s2["stow_angle"])
        elif "s2_stow" in servos_cfg: self.s2_stow = int(servos_cfg["s2_stow"])
        if "down_angle" in s2: self.s2_down = int(s2["down_angle"])
        elif "s2_down" in servos_cfg: self.s2_down = int(servos_cfg["s2_down"])
        if "min_angle" in s2: self.s2_min = int(s2["min_angle"])
        elif "s2_min" in servos_cfg: self.s2_min = int(servos_cfg["s2_min"])
        if "max_angle" in s2: self.s2_max = int(s2["max_angle"])
        elif "s2_max" in servos_cfg: self.s2_max = int(servos_cfg["s2_max"])
        if "center_angle" in s2: self.s2_center = int(s2["center_angle"])
        elif "s2_center" in servos_cfg: self.s2_center = int(servos_cfg["s2_center"])

        # S3 (Gripper)
        if "open_angle" in s3: self.s3_open = int(s3["open_angle"])
        elif "s3_open" in servos_cfg: self.s3_open = int(servos_cfg["s3_open"])
        if "close_angle" in s3: self.s3_close = int(s3["close_angle"])
        elif "s3_close" in servos_cfg: self.s3_close = int(servos_cfg["s3_close"])
