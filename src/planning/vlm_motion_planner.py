@dataclass
class VLMMotionPlan:
    """Structured motion and servo arm grab plan generated by VLM and kinematic planner."""
    action: str  # "DRIVE_FORWARD", "PIVOT_LEFT", "PIVOT_RIGHT", "NUDGE_FORWARD", "NUDGE_BACK", "NUDGE_LEFT", "NUDGE_RIGHT", "ALIGNED_GRASP", "STOP"
    recommended_pwm: int = 230  # Clamped >= min_overcoming_pwm
    duration_ms: int = 250  # Pulse duration for micro-nudges
    damping_factor: float = 1.0  # Speed scaling factor (0.5 to 1.0) to prevent overshoot
    base_speed: int = 230  # Baseline speed from robot config
    overshoot_risk: str = "LOW"  # "LOW", "MEDIUM", "HIGH"
    stiction_risk: str = "LOW"  # "LOW", "MEDIUM", "HIGH"
    alignment_status: str = "CENTERED"  # "CENTERED", "NEEDS_LEFT", "NEEDS_RIGHT"
    horizontal_error_px: int = 0  # dx = cx - sweet_x
    area_ratio: float = 0.0  # bbox_area / sweet_spot_area
    target_is_moving: bool = False  # True if target is dynamically moving in view
    movement_mode: str = "SMOOTH_FAST"  # "SMOOTH_FAST" (stationary target) or "SMOOTH_PULSE" (moving target)
    left_pwm: int = 0  # Planned left wheel PWM
    right_pwm: int = 0  # Planned right wheel PWM
    path_type: str = "CONTINUOUS_APPROACH"  # "CONTINUOUS_APPROACH", "ARC_ALIGN", "PIVOT_ALIGN", "HOLD_STANDOFF", "REVERSE_CLEAR", "STOP"
    is_overextended: bool = False  # True if target is closer than safe standoff distance (prevents over-extending)
    continuous_drive: bool = False  # True when robot cruises continuously along the planned efficient path
    distance_cm: float = 0.0
    target_dist_cm: float = 0.0
    target_info: Dict[str, Any] = field(default_factory=dict)
    arm_plan: Dict[str, Any] = field(default_factory=dict)  # Servo arm trajectory & calibrated grab sequence
    rationale: str = ""
    source: str = "VLM_HYBRID"  # "VLM_OLLAMA" or "VLM_KINEMATIC"
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action": self.action,
            "recommended_pwm": self.recommended_pwm,
            "left_pwm": self.left_pwm,
            "right_pwm": self.right_pwm,
            "duration_ms": self.duration_ms,
            "damping_factor": round(self.damping_factor, 2),
            "base_speed": self.base_speed,
            "overshoot_risk": self.overshoot_risk,
            "stiction_risk": self.stiction_risk,
            "alignment_status": self.alignment_status,
            "horizontal_error_px": self.horizontal_error_px,
            "area_ratio": round(self.area_ratio, 3),
            "target_is_moving": self.target_is_moving,
            "movement_mode": self.movement_mode,
            "path_type": self.path_type,
            "is_overextended": self.is_overextended,
            "continuous_drive": self.continuous_drive,
            "distance_cm": round(self.distance_cm, 1),
            "target_dist_cm": round(self.target_dist_cm, 1),
            "target_info": self.target_info,
            "arm_plan": self.arm_plan,
            "rationale": self.rationale,
            "source": self.source,
            "timestamp": self.timestamp
        }


